const ctx = document.querySelector("#picture").getContext("2d");
const ink = "#27354d";

function path(points, fill, stroke = ink, width = 3) {
  ctx.beginPath();
  points.forEach(([x, y], i) => i ? ctx.lineTo(x, y) : ctx.moveTo(x, y));
  if (fill) {
    ctx.closePath();
    ctx.fillStyle = fill;
    ctx.fill();
  }
  if (stroke) {
    ctx.strokeStyle = stroke;
    ctx.lineWidth = width;
    ctx.stroke();
  }
}

function oval(x, y, rx, ry, fill, stroke = ink) {
  ctx.beginPath();
  ctx.ellipse(x, y, rx, ry, 0, 0, Math.PI * 2);
  ctx.fillStyle = fill;
  ctx.fill();
  if (stroke) {
    ctx.strokeStyle = stroke;
    ctx.lineWidth = 3;
    ctx.stroke();
  }
}

function box(x, y, w, h, fill, stroke = ink) {
  path([[x, y], [x + w, y], [x + w, y + h], [x, y + h]], fill, stroke);
}

function star(x, y, r, color = "#ffe49c") {
  path([[x, y-r], [x+r*.23, y-r*.23], [x+r, y], [x+r*.23, y+r*.23],
    [x, y+r], [x-r*.23, y+r*.23], [x-r, y], [x-r*.23, y-r*.23]], color, null);
}

